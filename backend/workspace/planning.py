"""Versioned milestone and dependency planning, with project-wide graph locks."""
from django.db import transaction
from rest_framework import mixins, serializers, viewsets
from rest_framework.decorators import action
from rest_framework.generics import get_object_or_404
from rest_framework.response import Response
from .access import accessible_projects, current_membership, require_manager
from .models import AuditEvent, Milestone, Project, Task, TaskDependency
from .serializers import StrictSerializer
from .team_management import expected_version
from .development import lock_project


class MilestoneSerializer(StrictSerializer):
    completed = serializers.SerializerMethodField()
    total = serializers.SerializerMethodField()

    def get_completed(self, obj):
        return obj.tasks.filter(status='Done').count()

    def get_total(self, obj):
        return obj.tasks.count()

    def validate(self, attrs):
        project = attrs.get('project', self.instance.project if self.instance else None)
        if not project or not accessible_projects(current_membership(self.context['request'])).filter(pk=project.pk).exists():
            raise serializers.ValidationError('Choose an accessible project.')
        if self.instance and project.pk != self.instance.project_id:
            raise serializers.ValidationError('Moving a milestone is not supported.')
        start = attrs.get('start', self.instance.start if self.instance else None)
        due = attrs.get('due', self.instance.due if self.instance else None)
        if start and due and due < start:
            raise serializers.ValidationError('The end date must be on or after the start date.')
        return attrs

    class Meta:
        model = Milestone
        fields = ['id', 'project', 'title', 'kind', 'start', 'due', 'version', 'completed', 'total']
        read_only_fields = ['id']


class MilestoneViewSet(mixins.ListModelMixin, mixins.RetrieveModelMixin, mixins.CreateModelMixin, viewsets.GenericViewSet):
    serializer_class = MilestoneSerializer

    def get_queryset(self):
        return Milestone.objects.filter(project__in=accessible_projects(current_membership(self.request)))

    @transaction.atomic
    def perform_create(self, serializer):
        member = lock_project(current_membership(self.request), serializer.validated_data['project'])
        require_manager(member)
        if 'version' in serializer.validated_data:
            raise serializers.ValidationError('Version is generated by the server.')
        item = serializer.save()
        AuditEvent.objects.create(project=item.project, actor=self.request.user, action='milestone.created', text=f'Created {item.kind.lower()} {item.title}', after={'milestone_id': item.pk})

    @transaction.atomic
    def partial_update(self, request, pk=None):
        original = self.get_object()
        require_manager(lock_project(current_membership(request), original.project))
        item = get_object_or_404(self.get_queryset().select_for_update(), pk=pk)
        if not expected_version(request.data, item.version):
            return Response({'detail': 'Milestone changed. Refresh before saving.'}, status=409)
        serializer = self.get_serializer(item, data=request.data, partial=True)
        serializer.is_valid(raise_exception=True)
        before = self.get_serializer(item).data
        item = serializer.save(version=item.version + 1)
        AuditEvent.objects.create(project=item.project, actor=request.user, action='milestone.updated', text=f'Updated {item.title}', before=dict(before), after=dict(self.get_serializer(item).data))
        return Response(self.get_serializer(item).data)


class PlanningInput(serializers.Serializer):
    version = serializers.IntegerField(min_value=1)
    milestone = serializers.IntegerField(min_value=1, allow_null=True)
    dependency_ids = serializers.ListField(child=serializers.UUIDField(), max_length=200)

    def validate(self, attrs):
        if set(self.initial_data) != set(self.fields):
            raise serializers.ValidationError('Send version, milestone and dependency_ids only.')
        return attrs


class TaskPlanningMixin:
    @action(detail=True, methods=['put'])
    @transaction.atomic
    def planning(self, request, pk=None):
        original = self.get_object()
        require_manager(lock_project(current_membership(request), original.project))
        # All graph mutations acquire the same project lock before any task lock.
        Project.objects.select_for_update().get(pk=original.project_id)
        task = get_object_or_404(self.get_queryset().select_for_update(of=('self',)), pk=pk)
        serializer = PlanningInput(data=request.data)
        serializer.is_valid(raise_exception=True)
        data = serializer.validated_data
        if data['version'] != task.version:
            return Response({'detail': 'Task changed. Refresh before saving.'}, status=409)
        ids = set(data['dependency_ids'])
        if task.pk in ids or Task.objects.filter(pk__in=ids, project=task.project).count() != len(ids):
            raise serializers.ValidationError('Dependencies must be other tasks in this project.')
        milestone = None
        if data['milestone']:
            milestone = get_object_or_404(Milestone, pk=data['milestone'], project=task.project)
        graph = {}
        for source, target in TaskDependency.objects.filter(task__project=task.project).exclude(task=task).values_list('task_id', 'depends_on_id'):
            graph.setdefault(source, set()).add(target)
        graph[task.pk] = ids
        stack, seen = list(ids), set()
        while stack:
            current = stack.pop()
            if current == task.pk:
                raise serializers.ValidationError('This dependency would create a cycle.')
            if current not in seen:
                seen.add(current)
                stack.extend(graph.get(current, []))
        if task.status in ['In progress', 'In review', 'Done'] and Task.objects.filter(pk__in=ids).exclude(status='Done').exists():
            raise serializers.ValidationError('Move this task to To do or Blocked before adding unfinished dependencies.')
        before = {'milestone': task.milestone_id, 'dependency_ids': [str(v) for v in task.dependencies.values_list('depends_on_id', flat=True)]}
        task.dependencies.all().delete()
        TaskDependency.objects.bulk_create([TaskDependency(task=task, depends_on_id=i) for i in ids])
        task.milestone = milestone
        task.version += 1
        task.save(update_fields=['milestone', 'version', 'updated_at'])
        AuditEvent.objects.create(project=task.project, task=task, actor=request.user, action='task.planning', text=f'Updated planning for {task.title}', before=before, after={'milestone': task.milestone_id, 'dependency_ids': sorted(str(v) for v in ids)})
        return Response(self.get_serializer(task).data)
