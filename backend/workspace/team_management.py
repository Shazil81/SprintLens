"""Organization administration and versioned project/team management endpoints."""
from django.contrib.auth import get_user_model
from django.contrib.auth.password_validation import validate_password
from django.core.exceptions import ValidationError as DjangoValidationError
from django.db import IntegrityError, transaction
from rest_framework import mixins, serializers, viewsets
from rest_framework.decorators import action
from rest_framework.exceptions import PermissionDenied
from rest_framework.generics import get_object_or_404
from rest_framework.response import Response
from .access import accessible_projects, current_membership, require_manager
from .models import AuditEvent, Blocker, Membership, Organization, Project, ProjectMembership, Task
from .serializers import MemberSerializer, ProjectSerializer


def require_admin(member):
    if member.role != Membership.Role.ADMIN:
        raise PermissionDenied('Only workspace admins can create accounts or change organization roles.')


def expected_version(data, version):
    value = data.get('version')
    if isinstance(value, bool) or not isinstance(value, int):
        raise serializers.ValidationError({'version': 'Send the current integer project version.'})
    return value == version


def project_snapshot(project):
    return {key: str(getattr(project, key)) for key in ['name', 'code', 'description', 'due', 'color', 'version']}


class ProjectManagementViewSet(mixins.ListModelMixin, mixins.RetrieveModelMixin, mixins.CreateModelMixin, viewsets.GenericViewSet):
    serializer_class = ProjectSerializer

    def get_queryset(self):
        return accessible_projects(current_membership(self.request)).prefetch_related('memberships')

    @transaction.atomic
    def perform_create(self, serializer):
        member = current_membership(self.request)
        require_manager(member)
        # Serialize project code checks within this organization, including concurrent creates.
        Organization.objects.select_for_update().get(pk=member.organization_id)
        require_manager(current_membership(self.request))
        if 'version' in serializer.validated_data:
            raise serializers.ValidationError({'version': 'Project versions are generated by the server.'})
        if Project.objects.filter(organization=member.organization, code=serializer.validated_data['code']).exists():
            raise serializers.ValidationError({'code': 'This project code already exists.'})
        project = serializer.save(organization=member.organization)
        ProjectMembership.objects.create(project=project, membership=member, is_reviewer=member.role == Membership.Role.MANAGER)
        AuditEvent.objects.create(organization=member.organization, project=project, actor=self.request.user,
                                  action='project.created', text=f'Created project {project.name}', after=project_snapshot(project))

    @transaction.atomic
    def partial_update(self, request, pk=None):
        member = current_membership(request)
        require_manager(member)
        project = get_object_or_404(self.get_queryset().select_for_update(of=('self',)), pk=pk)
        if not expected_version(request.data, project.version):
            return Response({'detail': 'Project changed. Close this form, refresh, and try again.'}, status=409)
        serializer = self.get_serializer(project, data=request.data, partial=True)
        serializer.is_valid(raise_exception=True)
        if serializer.validated_data.get('code', project.code) != project.code:
            raise serializers.ValidationError({'code': 'The project code cannot change after creation.'})
        before = project_snapshot(project)
        updates = dict(serializer.validated_data)
        updates.pop('version', None)
        if not any(getattr(project, key) != value for key, value in updates.items()):
            return Response(self.get_serializer(project).data)
        project = serializer.save(version=project.version + 1)
        AuditEvent.objects.create(organization=member.organization, project=project, actor=request.user,
                                  action='project.updated', text=f'Updated project {project.name}', before=before, after=project_snapshot(project))
        return Response(self.get_serializer(project).data)

    @action(detail=True, methods=['put'])
    @transaction.atomic
    def members(self, request, pk=None):
        member = current_membership(request)
        require_manager(member)
        # Match the organization -> project lock order used by role changes and feedback.
        Organization.objects.select_for_update().get(pk=member.organization_id)
        member = current_membership(request)
        require_manager(member)
        project = get_object_or_404(self.get_queryset().select_for_update(of=('self',)), pk=pk)
        if not expected_version(request.data, project.version):
            return Response({'detail': 'Project changed. Close this form, refresh, and try again.'}, status=409)
        if set(request.data) - {'member_ids', 'reviewer_ids', 'version'}:
            raise serializers.ValidationError('Send only member_ids, reviewer_ids and version.')
        ids = request.data.get('member_ids')
        if not isinstance(ids, list) or len(ids) > 500 or any(isinstance(i, bool) or not isinstance(i, int) or i <= 0 for i in ids):
            raise serializers.ValidationError({'member_ids': 'Send a list of valid membership IDs (maximum 500).'})
        ids = set(ids)
        selected = Membership.objects.filter(pk__in=ids, organization=member.organization, user__is_active=True)
        if selected.count() != len(ids):
            raise serializers.ValidationError({'member_ids': 'Every member must be active and belong to this workspace.'})
        if member.role == Membership.Role.MANAGER and member.pk not in ids:
            raise serializers.ValidationError({'member_ids': 'A manager must retain their own project access.'})
        old_ids = set(project.memberships.values_list('membership_id', flat=True))
        old_reviewers = set(project.memberships.filter(is_reviewer=True).values_list('membership_id', flat=True))
        reviewers = request.data.get('reviewer_ids', sorted(old_reviewers & ids))
        if not isinstance(reviewers, list) or len(reviewers) > 500 or any(isinstance(i, bool) or not isinstance(i, int) for i in reviewers):
            raise serializers.ValidationError({'reviewer_ids': 'Send a list of membership IDs.'})
        reviewers = set(reviewers)
        if not reviewers <= ids or selected.filter(pk__in=reviewers, role__in=['Admin', 'Manager']).count() != len(reviewers):
            raise serializers.ValidationError({'reviewer_ids': 'Reviewers must be selected project members with Manager or Admin roles.'})
        # Managers can maintain the roster but cannot grant themselves reviewer permissions.
        if reviewers != old_reviewers & ids and member.role != Membership.Role.ADMIN:
            raise PermissionDenied('Only workspace admins can assign project reviewers.')
        removed = old_ids - ids
        if Task.objects.filter(project=project, assignee_id__in=removed).exclude(status='Done').exists():
            raise serializers.ValidationError({'member_ids': 'Reassign or finish open tasks before removing their assignees.'})
        if Blocker.objects.filter(task__project=project, owner_id__in=removed, resolved_at__isnull=True).exists():
            raise serializers.ValidationError({'member_ids': 'Resolve open blockers before removing their owners.'})
        if old_ids == ids and old_reviewers == reviewers:
            return Response(self.get_serializer(project).data)
        project.memberships.filter(membership_id__in=removed).delete()
        for selected_member in selected:
            ProjectMembership.objects.get_or_create(project=project, membership=selected_member)
        project.memberships.update(is_reviewer=False)
        project.memberships.filter(membership_id__in=reviewers).update(is_reviewer=True)
        project.version += 1
        project.save(update_fields=['version'])
        AuditEvent.objects.create(organization=member.organization, project=project, actor=request.user,
                                  action='project.members_changed', text=f'Updated team for {project.name}',
                                  before={'member_ids': sorted(old_ids), 'reviewer_ids': sorted(old_reviewers)},
                                  after={'member_ids': sorted(ids), 'reviewer_ids': sorted(reviewers)})
        return Response(self.get_serializer(project).data)


class AccountCreateSerializer(serializers.Serializer):
    username = serializers.CharField(max_length=150)
    first_name = serializers.CharField(max_length=150)
    last_name = serializers.CharField(max_length=150, required=False, allow_blank=True, default='')
    password = serializers.CharField(write_only=True, max_length=128, trim_whitespace=False)
    role = serializers.ChoiceField(choices=Membership.Role.choices)

    def validate(self, attrs):
        if set(self.initial_data) - set(self.fields):
            raise serializers.ValidationError('Unexpected account fields.')
        user = get_user_model()(username=attrs['username'], first_name=attrs['first_name'], last_name=attrs['last_name'])
        user.full_clean(exclude=['password', 'date_joined'])
        try:
            validate_password(attrs['password'], user)
        except DjangoValidationError as error:
            raise serializers.ValidationError({'password': error.messages})
        return attrs


class TeamManagementViewSet(mixins.ListModelMixin, mixins.CreateModelMixin, viewsets.GenericViewSet):
    serializer_class = MemberSerializer

    def get_queryset(self):
        member = current_membership(self.request)
        qs = Membership.objects.filter(organization=member.organization, user__is_active=True).select_related('user').order_by('id')
        if member.role == Membership.Role.DEVELOPER:
            qs = qs.filter(projects__project__in=accessible_projects(member)).distinct()
        return qs

    @transaction.atomic
    def create(self, request):
        member = current_membership(request)
        require_admin(member)
        Organization.objects.select_for_update().get(pk=member.organization_id)
        require_admin(current_membership(request))
        serializer = AccountCreateSerializer(data=request.data)
        try:
            serializer.is_valid(raise_exception=True)
        except DjangoValidationError as error:
            raise serializers.ValidationError(error.message_dict)
        values = dict(serializer.validated_data)
        role = values.pop('role')
        try:
            # A savepoint lets us turn a concurrent duplicate username into a client error.
            with transaction.atomic():
                user = get_user_model().objects.create_user(**values)
        except IntegrityError:
            raise serializers.ValidationError({'username': 'This username is unavailable.'})
        target = Membership.objects.create(organization=member.organization, user=user, role=role)
        AuditEvent.objects.create(organization=member.organization, actor=request.user, action='member.created',
                                  text=f'Added {user.get_full_name()} to the workspace',
                                  after={'member_id': target.pk, 'username': user.username, 'role': role})
        return Response(MemberSerializer(target).data, status=201)

    @transaction.atomic
    def partial_update(self, request, pk=None):
        member = current_membership(request)
        require_admin(member)
        # Lock the organization so two admins cannot concurrently remove the last admin role.
        Organization.objects.select_for_update().get(pk=member.organization_id)
        # A waiting request may have lost its admin role while another request held the lock.
        require_admin(current_membership(request))
        target = get_object_or_404(self.get_queryset().select_for_update(of=('self',)), pk=pk)
        if set(request.data) != {'role'} or request.data['role'] not in Membership.Role.values:
            raise serializers.ValidationError({'role': 'Send only a valid workspace role.'})
        role = request.data['role']
        if role == target.role:
            return Response(MemberSerializer(target).data)
        if target.role == Membership.Role.ADMIN and role != Membership.Role.ADMIN:
            if Membership.objects.filter(organization=member.organization, role='Admin', user__is_active=True).count() <= 1:
                raise serializers.ValidationError({'role': 'The workspace must retain at least one active admin.'})
        if target.pk == member.pk:
            raise serializers.ValidationError({'role': 'Ask another admin to change your own role.'})
        previous = target.role
        target.role = role
        target.save(update_fields=['role'])
        AuditEvent.objects.create(organization=member.organization, actor=request.user, action='member.role_changed',
                                  text=f'Changed {target.user.get_full_name() or target.user.username} role to {role}',
                                  before={'member_id': target.pk, 'role': previous}, after={'member_id': target.pk, 'role': role})
        return Response(MemberSerializer(target).data)
